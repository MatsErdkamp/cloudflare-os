import {createHash} from "node:crypto";
import {readFile, writeFile} from "node:fs/promises";
import {createRequire} from "node:module";
import {dirname, relative, resolve} from "node:path";
import {fileURLToPath} from "node:url";

const packageRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const generatedPath = resolve(packageRoot, "src/generated/comparison-generator-identity.ts");
const generatedSpecifier = "./generated/comparison-generator-identity.js";
const require = createRequire(import.meta.url);

async function collectLocalRuntimeClosure(entryPath) {
  const pending = [entryPath];
  const sources = new Map();
  while (pending.length > 0) {
    const path = pending.pop();
    if (sources.has(path)) continue;
    const source = await readFile(path, "utf8");
    sources.set(path, source);
    for (const match of source.matchAll(/(?:import|export)\s+(?!type\b)[\s\S]*?from\s+["'](\.[^"']+)["']/g)) {
      const specifier = match[1];
      if (specifier === generatedSpecifier) continue;
      const sourceSpecifier = specifier.replace(/\.js$/, ".ts");
      pending.push(resolve(dirname(path), sourceSpecifier));
    }
  }
  return [...sources]
    .map(([path, source]) => ({path: relative(packageRoot, path), source}))
    .toSorted((left, right) => left.path.localeCompare(right.path));
}

const [sources, tsconfig, typescriptPackage] = await Promise.all([
  collectLocalRuntimeClosure(resolve(packageRoot, "src/comparison.ts")),
  readFile(resolve(packageRoot, "tsconfig.json"), "utf8"),
  readFile(require.resolve("typescript/package.json"), "utf8"),
]);
const compilerVersion = JSON.parse(typescriptPackage).version;
const manifest = JSON.stringify({compiler: {name: "typescript", version: compilerVersion}, sources, tsconfig});
const identity = `sha256:${createHash("sha256").update(manifest).digest("hex")}`;
const output = `// Generated by scripts/build-comparison-generator-identity.mjs.\n` +
  `// Exact source closure, compiler, and transform configuration are covered by this digest.\n` +
  `export const COMPARISON_GENERATOR_IDENTITY = ${JSON.stringify(identity)};\n`;
let current;
try { current = await readFile(generatedPath, "utf8"); } catch {}
if (current !== output) await writeFile(generatedPath, output);
